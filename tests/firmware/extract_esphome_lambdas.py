#!/usr/bin/env python3
"""Extract the VE.Direct lambdas from the ESPHome YAML into a C++ header.

ESPHome pastes every ``lambda: |-`` block verbatim into a C++ function body.
This script does the same for the three VE.Direct lambdas of
``firmware/esphome_smdc_bridge.yaml`` so that ``test_esphome_lambda.cpp`` can
compile and run the very text that ships, against host stubs. Nothing is
rewritten: if the YAML changes, the tests exercise the changed code.

Standard library only (no PyYAML): a block scalar is simply every following
line that is blank or indented deeper than its ``lambda:`` key.

Usage: extract_esphome_lambdas.py <esphome.yaml> <output.h>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

# name of the generated function -> (return type, text that identifies the lambda)
WANTED = {
    "smdc_ve_parser_lambda": ("void", "VE_RECORD_HEX"),
    "smdc_ve_watchdog_lambda": ("void", "VE_STALE_AFTER_MS"),
    "smdc_ve_frame_age_lambda": ("float", "static_cast<uint32_t>(millis() - id(ve_last_valid_ms))"),
}

LAMBDA_KEY = re.compile(r"^(?P<indent>\s*)(?:-\s+)?lambda:\s*\|[-+]?\s*$")


def block_scalars(lines: list[str]) -> list[tuple[int, list[str]]]:
    """Return (1-based first line number, dedented lines) of every lambda block."""
    blocks = []
    i = 0
    while i < len(lines):
        match = LAMBDA_KEY.match(lines[i])
        if not match:
            i += 1
            continue
        key_indent = len(match.group("indent"))
        body = []
        j = i + 1
        while j < len(lines):
            line = lines[j]
            if line.strip() and len(line) - len(line.lstrip(" ")) <= key_indent:
                break
            body.append(line)
            j += 1
        while body and not body[-1].strip():
            body.pop()
        indents = [len(line) - len(line.lstrip(" ")) for line in body if line.strip()]
        cut = min(indents) if indents else 0
        blocks.append((i + 2, [line[cut:] if line.strip() else "" for line in body]))
        i = j
    return blocks


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    source = Path(argv[1])
    target = Path(argv[2])
    blocks = block_scalars(source.read_text(encoding="utf-8").splitlines())

    out = [
        f"// GENERATED by tests/firmware/extract_esphome_lambdas.py from {source.name} - do not edit.",
        "// Each function body is the unmodified text of one `lambda: |-` block.",
        "",
    ]
    for function, (return_type, marker) in WANTED.items():
        matches = [block for block in blocks if any(marker in line for line in block[1])]
        if len(matches) != 1:
            print(
                f"error: expected exactly one lambda containing {marker!r} in {source}, found {len(matches)}",
                file=sys.stderr,
            )
            return 1
        first_line, body = matches[0]
        out.append(f"// {source.name}:{first_line}")
        out.append(f"static {return_type} {function}() {{")
        out.extend(body)
        out.append("}")
        out.append("")
    target.write_text("\n".join(out), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
