def tool_get_telemetry(params: dict[str, Any]) -> dict[str, Any]:
    """Retrieves power, thermal, storage, and GPU hardware telemetry.

    ``is_simulated`` on the power and thermal sections (and the top-level
    ``telemetry_simulated``) tells the caller whether those readings were measured or
    generated by the simulator. A quantity the source did not report is ``null``
    (battery voltage, solar power, system load, net power, rack air temperatures); it is
    never replaced by a nominal value.
    """
    power = read_power(exporter_url=get_config().power_exporter_url, simulation=get_config().is_simulation())
    thermal = read_thermal(exporter_url=get_config().power_exporter_url, simulation=get_config().is_simulation())
    storage = detect_storage()
    gpus = detect_gpus()

    return {
        "timestamp": time.time(),
        "telemetry_simulated": bool(power.is_simulated or thermal.is_simulated),
        "power": {
            "battery_soc_percent": power.battery_soc,
            "battery_voltage_volts": power.battery_voltage,
            "solar_pv_watts": power.solar_watts,
            "system_load_watts": power.system_load_watts,
            "net_power_watts": round(power.net_power, 2) if power.net_power is not None else None,
            "load_shedding_active": power.load_shedding_active,
            "is_simulated": bool(power.is_simulated),
        },
        "thermal": {
            "coolant_celsius": thermal.coolant_celsius,
            "rack_inlet_celsius": thermal.rack_inlet_celsius,
            "rack_exhaust_celsius": thermal.rack_exhaust_celsius,
            "is_overtemp": thermal.is_overtemp,
            "is_simulated": bool(thermal.is_simulated),
        },
        "storage": {
            "total_gb": storage.total_gb,
            "used_gb": storage.used_gb,
            "free_gb": storage.free_gb,
            "usage_percent": round(storage.usage_percent, 1),
        },
        "gpu": {
            "count": len(gpus),
            "devices": [
                {
                    "name": g.name,
                    "memory_mb": g.memory_mb,
                    "status": g.status,
                }
                for g in gpus
            ],
        },
    }


def tool_get_system_status(params: dict[str, Any]) -> dict[str, Any]:
    """Retrieves full micro-datacenter system status, load shedding, and node role."""
    from sovereign_dc.economy.market import ComputeMarket
    from sovereign_dc.space.dtn.router import DTNRouter

    cfg = get_config()
    power = read_power(exporter_url=get_config().power_exporter_url, simulation=get_config().is_simulation())
    thermal = read_thermal(exporter_url=get_config().power_exporter_url, simulation=get_config().is_simulation())
    router = DTNRouter(db_path=cfg.dtn_db_path)
    dtn_stats = router.get_queue_stats()
    market = ComputeMarket()
    mult, market_status = market.get_dynamic_multiplier(power.battery_soc, power.solar_watts)

    return {
        "node_id": cfg.node_id,
        "role": cfg.node_role,
        "version": __version__,
        "is_simulation": cfg.hal_mode == "simulation",
        # Provenance of the readings behind "health", "load_shedding" and "market".
        "telemetry_simulated": bool(power.is_simulated or thermal.is_simulated),
        "health": "CRITICAL" if thermal.is_overtemp else ("WARNING" if power.load_shedding_active else "NOMINAL"),
        "load_shedding": {
            "active": power.load_shedding_active,
            # Same tiers as the sentinel: SovereignConfig.shedding_l1..l4_soc (50/30/20/10 %).
            "recommended_level": f"L{cfg.get_shedding_level(power.battery_soc)}",
        },
        "market": {
            "multiplier": mult,
            "status": market_status,
        },
        "dtn_spool": dtn_stats,
    }


def tool_set_load_shedding(params: dict[str, Any]) -> dict[str, Any]:
    """Publishes a load-shedding level change on the in-process event bus.

    This does not actuate hardware (no PDU, GPU or TDP control is driven from here): the
    only effect is the ``load_shedding.changed`` event carrying ``level`` and ``mode``
    (no ``battery_soc`` reading), to which the EnterpriseManager reacts by pausing/resuming
    tracked apps by power tier (``schema.SHED_PAUSE_LEVEL``); apps held paused by their
    ``min_battery_soc`` floor stay paused until an event carrying ``battery_soc`` clears
    that cause. ``description`` and ``paused_tiers`` state that implemented effect;
    ``design_targets_not_implemented`` lists the hardware actions the design foresees.
    """
    from sovereign_dc.enterprise.schema import SHED_PAUSE_LEVEL
    from sovereign_dc.events import Event, EventType, get_event_bus

    level = str(params.get("level", "L0")).upper()
    valid_levels = ["L0", "L1", "L2", "L3", "L4"]
    if level not in valid_levels:
        return {
            "success": False,
            "error": f"Invalid level '{level}'. Must be one of {valid_levels}.",
        }

    numeric_level = int(level[1])
    # The implemented effect: which power tiers the EnterpriseManager marks paused.
    paused_tiers = sorted(tier.value for tier, pause_level in SHED_PAUSE_LEVEL.items() if numeric_level >= pause_level)
    if paused_tiers:
        description = (
            f"Tracked running enterprise apps of power tier {', '.join(paused_tiers)} are marked paused; "
            "L0_CRITICAL apps and running apps of other tiers keep running. Apps paused solely by tier "
            "shedding are resumed when the level falls below the one that pauses their tier; because "
            "this event carries no battery_soc reading, any app held paused by its min_battery_soc floor "
            "(and any operator-paused app) stays paused."
        )
    else:
        description = (
            "No power tier is paused; apps paused solely by tier shedding are resumed. Because this "
            "event carries no battery_soc reading, any app held paused by its min_battery_soc floor "
            "(and any operator-paused app) stays paused."
        )
    # Hardware actions the design foresees per level. None of them is driven by this tool
    # or by any other code path of this release.
    design_targets = {
        "L0": [],
        "L1": [],
        "L2": ["disable the secondary GPU", "throttle the primary compute module to 30 W TDP"],
        "L3": ["halt all GPU workloads", "keep only critical networking and BMS monitoring powered"],
        "L4": ["power down non-essential outlets through the PDU"],
    }

    # Ensure enterprise manager is subscribed and publish load shedding event
    get_enterprise_manager()
    handlers_notified = get_event_bus().publish(
        Event(
            event_type=EventType.LOAD_SHEDDING_CHANGED,
            source="mcp",
            payload={"level": numeric_level, "mode": level},
        )
    )
    published_at = time.time()

    return {
        "success": True,
        "level": level,
        "description": description,
        "paused_tiers": paused_tiers,
        "design_targets_not_implemented": design_targets[level],
        "effect": "event_published",
        "hardware_actuated": False,
        "handlers_notified": handlers_notified,
        "note": (
            "Only a load_shedding.changed event was published. 'description' and 'paused_tiers' are "
            "what the EnterpriseManager does with it (it tracks app state; it supervises no process); "
            "'design_targets_not_implemented' are hardware actions of the design that nothing drives."
        ),
        "published_at": published_at,
        "applied_at": published_at,
    }


def _node_solar_watts() -> tuple[float | None, str]:
    """The node's solar harvest and where it came from, without requiring a battery SoC.

    Used when the caller supplied the SoC but not the solar input. An exporter that is
    unreachable, reports its source down or has no finite solar sample gives ``(None,
    "unknown")``: an unknown harvest earns no discount and no value is invented.
    """
    from sovereign_dc.hal.power import METRIC_SIMULATED, METRIC_SOLAR_WATTS, fetch_exporter_metrics, optional_metric

    try:
        metrics = fetch_exporter_metrics(get_config().power_exporter_url)
    except Exception as exc:  # unreachable, source down, malformed
        logger.debug("No solar measurement for pricing: %s", exc)
        return None, "unknown"
    solar = optional_metric(metrics, METRIC_SOLAR_WATTS)
    if solar is None:
        return None, "unknown"
    return solar, "simulated_telemetry" if metrics.get(METRIC_SIMULATED, 0.0) > 0 else "measured_telemetry"


def tool_query_market_pricing(params: dict[str, Any]) -> dict[str, Any]:
    """Queries dynamic solar-aware compute, token, and DTN relay pricing rates."""
    from sovereign_dc.economy.market import ComputeMarket, ServiceType

    soc_given = params.get("battery_soc") is not None
    solar_given = params.get("solar_watts") is not None
    # Telemetry is read only for an input the caller did not supply. The battery SoC is the
    # one input that must exist; a missing solar reading is "unknown" (no discount).
    soc_in: Any = params.get("battery_soc")
    solar_in: Any = params.get("solar_watts")
    sources = {"battery_soc": "caller", "solar_watts": "caller"}
    if not soc_given:
        power = read_power(exporter_url=get_config().power_exporter_url, simulation=get_config().is_simulation())
        telemetry = "simulated_telemetry" if power.is_simulated else "measured_telemetry"
        soc_in, sources["battery_soc"] = power.battery_soc, telemetry
        if not solar_given:
            solar_in = power.solar_watts
            sources["solar_watts"] = telemetry if solar_in is not None else "unknown"
    elif not solar_given:
        solar_in, sources["solar_watts"] = _node_solar_watts()
    try:
        soc = float(soc_in)
        # None: the node has no solar measurement (an unknown harvest earns no discount).
        solar = float(solar_in) if solar_in is not None else None
        if not math.isfinite(soc) or (solar is not None and not math.isfinite(solar)):
            raise ValueError("non-finite value")
    except (TypeError, ValueError):
        return {"success": False, "error": "'battery_soc' and 'solar_watts' must be finite numbers"}
    telemetry_kinds = {v for v in sources.values() if v.endswith("_telemetry")}

    market = ComputeMarket()
    mult, status = market.get_dynamic_multiplier(soc, solar)
    catalog = {
        st.value: market.calculate_quote(st, 1.0, battery_soc=soc, solar_power_w=solar).to_dict() for st in ServiceType
    }

    return {
        "battery_soc_percent": soc,
        "solar_pv_watts": solar,
        # Where each input came from: "caller" (a what-if value), "measured_telemetry",
        # "simulated_telemetry" or "unknown" (no solar reading).
        "input_sources": sources,
        # Summary of the above: "caller" when both inputs are the caller's, "mixed" when one
        # is, otherwise the kind of telemetry used.
        "inputs_source": "caller"
        if soc_given and solar_given
        else ("mixed" if soc_given or solar_given else sources["battery_soc"]),
        # None: no telemetry value was used.
        "telemetry_simulated": ("simulated_telemetry" in telemetry_kinds) if telemetry_kinds else None,
        "dynamic_multiplier": mult,
        "market_condition": status,
        "service_rates": catalog,
        "currency": "SOV Credits",
    }


def tool_get_wallet_balances(params: dict[str, Any]) -> dict[str, Any]:
    """Inspects the node wallet addresses (Ed25519 and ML-DSA-87) and the node balance.

    This is the node's one identity (``sovereign_dc.economy.node_state``): the same wallet and
    ledger ``smdc economy wallet`` and the dashboard report. Nothing is minted here; a balance
    only exists after an operator ran ``smdc economy mint``, and those are locally issued test
    credits with no external value.
    """
    from sovereign_dc.economy.node_state import LOCAL_TEST_CREDIT_NOTICE, get_node_identity
    from sovereign_dc.economy.wallet import AddressType

    identity = get_node_identity(get_config().node_id)
    wallet = identity.wallet
    is_ed25519 = wallet.keypair.algorithm == AddressType.ED25519

    return {
        "node_id": wallet.node_id,
        # The wallet that holds the balance (Ed25519 unless a legacy ML-DSA wallet was adopted).
        "address": wallet.address,
        "algorithm": wallet.keypair.algorithm.value,
        "address_ed25519": wallet.address if is_ed25519 else None,
        "address_pqc_mldsa87": identity.pqc_wallet.address,
        "balance_sov": identity.balance,
        "credits_kind": "local_test_credits",
        "note": LOCAL_TEST_CREDIT_NOTICE,
    }


def tool_spool_dtn_bundle(params: dict[str, Any]) -> dict[str, Any]:
    """Creates and queues an (unsigned) RFC 9171 BPv7 bundle into the store-and-forward spool.

    Follows the node's DTN submission contract (``sovereign_dc.web.dashboard``), the same one
    the dashboard API and the enterprise SDK use: default priority NORMAL, default lifetime
    ``DTN_DEFAULT_TTL_SECONDS`` (an omitted ``ttl_seconds`` is left to the contract, never
    replaced by a value of this tool's own), validated TTL, source EID
    ``dtn://<node-id>/mcp`` unless a valid ``source`` is given.
    """
    from sovereign_dc.space.dtn.router import DTNRouter
    from sovereign_dc.web.dashboard import (
        DTN_DEFAULT_DESTINATION,
        DTN_PRIORITY_NAMES,
        describe_dtn_bundle,
        parse_dtn_submission,
    )

    cfg = get_config()
    # The advertised schema cannot say "one of payload / payload_b64" without a top-level
    # JSON-Schema combinator (which several MCP clients reject), so the rule is enforced here.
    if params.get("payload") is None and params.get("payload_b64") is None:
        return {
            "success": False,
            "signed": False,
            "status": "REJECTED",
            "error": (
                "Bundle was not queued: provide 'payload' (text) or 'payload_b64' (base64, for binary data); "
                "neither was given."
            ),
        }
    request: dict[str, Any] = {"destination": params.get("destination", DTN_DEFAULT_DESTINATION)}
    if params.get("payload") is not None:
        request["payload"] = str(params["payload"])
    if params.get("ttl_seconds") is not None:
        request["ttl"] = params["ttl_seconds"]
    for key in ("payload_b64", "priority", "source"):
        if params.get(key) is not None:
            request[key] = params[key]
    # MCP clients sometimes send integers as numeric strings; anything else is left for
    # the contract to reject by name.
    for key in ("priority", "ttl"):
        value = request.get(key)
        if isinstance(value, str) and value.strip().lstrip("-").isdigit():
            request[key] = int(value)

    try:
        submission = parse_dtn_submission(request, cfg.node_id, service="mcp")
    except ValueError as e:
        return {
            "success": False,
            "signed": False,
            "status": "REJECTED",
            "error": f"Bundle was not queued: {e}",
        }

    bundle = submission.to_bundle()
    router = DTNRouter(db_path=cfg.dtn_db_path)
    queued = router.queue_bundle(bundle)

    stored = describe_dtn_bundle(bundle, ttl_capped=submission.ttl_capped)
    result: dict[str, Any] = {
        "success": bool(queued),
        **stored,
        # Kept for compatibility: "priority" is the level name; the number is "priority_level".
        "priority": DTN_PRIORITY_NAMES[bundle.priority],
        "priority_level": bundle.priority,
        "signed": False,
        "status": "QUEUED_IN_NVME_SPOOL" if queued else "REJECTED",
    }
    if not queued:
        result["error"] = (
            "Bundle was rejected by the DTN router and was not queued "
            f"(lifetime {bundle.lifetime_seconds}s: already expired or invalid)."
        )
    return result


def tool_predict_satellite_passes(params: dict[str, Any]) -> dict[str, Any]:
    """Predicts upcoming satellite contact windows with the built-in simplified orbit model.

    The propagator is a circular-orbit, two-body approximation (no SGP4, no perturbations or
    drag), so the windows are planning estimates, not tracking-grade predictions.
    """
    from sovereign_dc.space.orbital.propagator import GroundStation
    from sovereign_dc.space.orbital.tle_updater import get_active_satellites

    cfg = get_config()
    hours = max(0.1, min(float(params.get("duration_hours", 12.0)), 168.0))
    min_elev = max(0.0, min(float(params.get("min_elevation_deg", 10.0)), 90.0))

    satellites = get_active_satellites()
    gs = GroundStation(cfg.ground_station_name, cfg.ground_station_lat, cfg.ground_station_lon)

    results: list[dict[str, Any]] = []
    for sat in satellites:
        passes = gs.predict_passes(sat, duration_hours=hours, min_elevation_deg=min_elev)
        for p in passes:
            results.append(
                {
                    "satellite_name": p.get("satellite", sat.name),
                    "norad_id": p.get("norad_id", sat.norad_id),
                    "aos_time": p.get("aos_time", 0),
                    "los_time": p.get("los_time", 0),
                    "duration_seconds": p.get("duration_seconds", 0),
                    "max_elevation_deg": p.get("max_elevation", 0.0),
                }
            )

    results.sort(key=lambda x: x.get("aos_time", 0))

    return {
        "ground_station": {
            "name": cfg.ground_station_name,
            "lat": cfg.ground_station_lat,
            "lon": cfg.ground_station_lon,
        },
        "forecast_hours": hours,
        "orbit_model": "simplified circular two-body propagation (not SGP4; approximate)",
        "total_passes_found": len(results),
        "passes": results[:10],
    }


def tool_query_knowledge_indexer(params: dict[str, Any]) -> dict[str, Any]:
    """Keyword search over the Markdown documentation in the server's working directory.

    This is a case-insensitive substring match of the query's words (longer than two
    characters) against paragraphs of ``*.md`` and ``hardware/*.md``. It is not semantic or
    vector search and does not query the Qdrant index built by the knowledge indexer agent.
    ``keyword_score`` is the fraction of query words found in the paragraph.
    """
    query = str(params.get("query", "solar power management")).lower()
    limit = max(1, min(int(params.get("limit", 3)), 50))

    cwd = os.getcwd()
    doc_files = sorted(glob.glob(os.path.join(cwd, "*.md")) + glob.glob(os.path.join(cwd, "hardware", "*.md")))
    words = sorted({w for w in query.split() if len(w) > 2})

    chunks: list[dict[str, Any]] = []
    for fpath in doc_files:
        try:
            with open(fpath, encoding="utf-8", errors="ignore") as f:
                content = f.read()
        except OSError as exc:
            logger.debug("Error reading doc file %s: %s", fpath, exc)
            continue
        for para in content.split("\n\n"):
            para_clean = para.strip()
            if not para_clean:
                continue
            para_lower = para_clean.lower()
            matched = [w for w in words if w in para_lower]
            if matched:
                chunks.append(
                    {
                        "source": os.path.basename(fpath),
                        "text": para_clean[:350] + ("..." if len(para_clean) > 350 else ""),
                        "matched_terms": matched,
                        "keyword_score": round(len(matched) / len(words), 2),
                    }
                )

    chunks.sort(key=lambda x: x["keyword_score"], reverse=True)
    return {
        "query": query,
        "search_mode": "keyword",
        "search_terms": words,
        "documents_searched": len(doc_files),
        "results_count": len(chunks[:limit]),
        "chunks": chunks[:limit],
    }


def tool_run_security_audit(params: dict[str, Any]) -> dict[str, Any]:
    """Runs FIPS 204 ML-DSA-87 and FIPS 203 ML-KEM-1024 round-trip self-tests.

    This is a functional self-test of the PQC engines only. It does not inspect mesh
    encryption, node identity or any other NIST SP 800-207 Zero Trust control, so that
    section is reported as NOT_ASSESSED.
    """
    from sovereign_dc.security.pqc import PQCKEM, PQCAlgorithm, PQCSigner

    signer = PQCSigner(PQCAlgorithm.ML_DSA_87)
    sig_kp = signer.generate_keypair()

    test_msg = b"SOVEREIGN_NODE_ATTESTATION"
    sig = signer.sign(test_msg, sig_kp.private_key)
    sig_valid = signer.verify(test_msg, sig, sig_kp.public_key)

    kem = PQCKEM(PQCAlgorithm.ML_KEM_1024)
    kem_kp = kem.generate_keypair()
    ct, ss_client = kem.encapsulate(kem_kp.public_key)
    ss_server = kem.decapsulate(ct, kem_kp.private_key)
    kem_valid = ss_client == ss_server

    return {
        "timestamp": time.time(),
        "nist_sp_800_207_zero_trust": {
            "status": "NOT_ASSESSED",
            "note": "No Zero Trust controls (mesh encryption, node identity, policy enforcement) are inspected by this tool.",
        },
        "post_quantum_attestation": {
            "digital_signatures": {
                "algorithm": "NIST FIPS 204 ML-DSA-87",
                "test_verification": "PASSED" if sig_valid else "FAILED",
                "public_key_bytes": len(sig_kp.public_key),
            },
            "key_encapsulation": {
                "algorithm": "NIST FIPS 203 ML-KEM-1024",
                "test_decapsulation": "PASSED" if kem_valid else "FAILED",
                "ciphertext_bytes": len(ct),
            },
        },
        "pqc_self_tests_passed": int(sig_valid) + int(kem_valid),
        "pqc_self_tests_total": 2,
        # Kept for compatibility: this is the share of PQC self-tests that passed
        # (two-step scale), not a compliance assessment.
        "compliance_score_percent": 100.0 if (sig_valid and kem_valid) else 50.0,
        "score_basis": "pqc_self_tests_only",
    }


def tool_dispatch_technician_alert(params: dict[str, Any]) -> dict[str, Any]:
    """Dispatches emergency hardware maintenance alert over LoRa, MQTT, DTN, or File."""
    from sovereign_dc.agents.technician_notifier import MessageSeverity, TechnicianNotifierChain

    message = str(params.get("message", "Routine automated diagnostic dispatch."))
    severity_str = str(params.get("severity", "INFO")).upper()
    severity_map = {
        "INFO": MessageSeverity.INFO,
        "WARNING": MessageSeverity.WARNING,
        "ERROR": MessageSeverity.ERROR,
        "CRITICAL": MessageSeverity.CRITICAL,
    }
    sev = severity_map.get(severity_str, MessageSeverity.INFO)

    notifier = TechnicianNotifierChain()
    channel_results = notifier.notify(
        event_type="MCP_ALERT",
        severity=sev,
        message=message,
        details={"dispatched_via": "mcp"},
    )

    return {
        "dispatched": True,
        "message": message,
        "severity": severity_str,
        "channels": channel_results,
        "timestamp": time.time(),
    }


