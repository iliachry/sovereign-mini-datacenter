def tool_list_enterprise_apps(params: dict[str, Any]) -> dict[str, Any]:
    """Lists all registered enterprise applications and live runtime states."""
    manager = get_enterprise_manager()
    states = manager.list_runtime_states()
    return {
        "count": len(states),
        "apps": [s.to_dict() for s in states],
    }


def tool_manage_enterprise_app(params: dict[str, Any]) -> dict[str, Any]:
    """Controls application lifecycle (start, stop, restart, pause, resume)."""
    app_id = str(params.get("app_id", ""))
    action = str(params.get("action", "start"))
    manager = get_enterprise_manager()

    if action == "start":
        success, msg = manager.start_app(app_id)
    elif action == "stop":
        success, msg = manager.stop_app(app_id)
    elif action == "restart":
        success, msg = manager.restart_app(app_id)
    elif action == "pause":
        success, msg = manager.pause_app(app_id, reason=str(params.get("reason", "Operator request")))
    elif action == "resume":
        success, msg = manager.resume_app(app_id, reason=str(params.get("reason", "Operator request")))
    else:
        return {"success": False, "error": f"Unknown action: {action}"}

    state = manager.get_runtime_state(app_id)
    return {
        "success": success,
        "message": msg,
        "state": state.to_dict() if state else None,
    }


def tool_scaffold_enterprise_app(params: dict[str, Any]) -> dict[str, Any]:
    """Generates and validates an enterprise application manifest; returns it with a YAML preview.

    Nothing is written to disk (no target directory is accepted), so this tool can never
    overwrite an application's files. The project directory is created by ``smdc app init``,
    which refuses to replace existing files unless ``--force`` is passed.
    """
    from sovereign_dc.enterprise.registry import EnterpriseRegistry
    from sovereign_dc.enterprise.schema import AppCategory, PowerPriority, RuntimeType, slugify_app_id

    param_errors: list[str] = []

    raw_name = params.get("name", "Custom App")
    if not isinstance(raw_name, str) or not raw_name.strip():
        param_errors.append("Invalid 'name': must be a non-empty string.")
        name = "Custom App"
    else:
        name = raw_name

    raw_app_id = params.get("app_id")
    if raw_app_id is not None and not isinstance(raw_app_id, str):
        param_errors.append(f"Invalid 'app_id' {raw_app_id!r}: must be a string.")
        app_id = slugify_app_id(name)
    else:
        # An explicit string app_id is used verbatim (and reported invalid by manifest.validate() if malformed).
        app_id = slugify_app_id(name) if raw_app_id is None else raw_app_id

    def _enum_arg(key: str, enum_cls: Any, default: Any) -> Any:
        raw = params.get(key)
        if raw is None:
            return default
        if isinstance(raw, str):
            try:
                return enum_cls(raw)
            except ValueError:
                pass
        allowed = [member.value for member in enum_cls]
        param_errors.append(f"Invalid '{key}' {raw!r}. Must be one of {allowed}.")
        return default

    category = _enum_arg("category", AppCategory, AppCategory.CUSTOM)
    runtime = _enum_arg("runtime", RuntimeType, RuntimeType.PROCESS)
    power_tier = _enum_arg("power_tier", PowerPriority, None)

    raw_gpu = params.get("gpu_required")
    if raw_gpu is not None and not isinstance(raw_gpu, bool):
        param_errors.append(f"Invalid 'gpu_required' {raw_gpu!r}. Must be a boolean.")
        gpu_required = None
    else:
        gpu_required = raw_gpu

    raw_entrypoint = params.get("entrypoint")
    if raw_entrypoint is not None and not isinstance(raw_entrypoint, str):
        param_errors.append(f"Invalid 'entrypoint' {raw_entrypoint!r}: must be a string.")
        entrypoint = "python3 app.py"
    else:
        entrypoint = "python3 app.py" if raw_entrypoint is None else raw_entrypoint

    if param_errors:
        return {
            "success": False,
            "valid": False,
            "error": param_errors[0],
            "validation_errors": param_errors,
            "manifest": None,
            "yaml_preview": "",
        }

    manifest = EnterpriseRegistry.scaffold_manifest(
        name=name,
        app_id=app_id,
        category=category,
        runtime=runtime,
        entrypoint=entrypoint,
        gpu_required=gpu_required,
        power_tier=power_tier,
    )
    errors = manifest.validate()
    return {
        "manifest": manifest.to_dict(),
        "valid": not errors,
        "validation_errors": errors,
        "yaml_preview": EnterpriseRegistry.render_manifest_yaml(manifest),
    }


def tool_run_metaverse_sim_cycle(params: dict[str, Any]) -> dict[str, Any]:
    """Executes multi-layer metaverse simulation cycles (Algorithm 1: SA-PPO, Sionna Ray-Tracing, 5G Slicing, DePIN SLA).

    Without ``seed`` the cycles run on this process's shared orchestrator, the one the
    ``get_5g_slices_status`` tool, the ``metaverse`` resources and (in the dashboard process)
    ``/api/metaverse/*`` read, so those reflect the run. With ``seed`` a separate orchestrator
    seeded with it runs the cycles (a reproducible run from a fresh state) and is discarded:
    the result says so, and the shared orchestrator is left untouched.
    """
    from sovereign_dc.metaverse.engine import MetaverseOrchestrator
    from sovereign_dc.web.dashboard import get_metaverse_orchestrator

    cycles = max(1, min(int(params.get("cycles", 1)), 100))
    deterministic = bool(params.get("deterministic", True))
    raw_seed = params.get("seed")

    result: dict[str, Any]
    if raw_seed is None:
        orch = get_metaverse_orchestrator()
        traces = orch.run_cycles(count=cycles, deterministic=deterministic)
        result = {
            "orchestrator": "process_orchestrator",
            "note": "Ran on this process's shared orchestrator: the status tools and resources reflect these cycles.",
        }
    else:
        seed = int(raw_seed)
        orch = MetaverseOrchestrator(seed=seed)
        traces = orch.run_cycles(count=cycles, deterministic=deterministic)
        result = {
            "orchestrator": "separate_seeded_run",
            "seed": seed,
            "note": (
                "A seed was passed, so a separate orchestrator seeded with it ran these cycles from a fresh "
                "state and was discarded: get_5g_slices_status and the other status tools do not reflect them. "
                "Omit 'seed' to run on the shared process orchestrator."
            ),
        }

    result.update(
        {
            "cycles_executed": len(traces),
            "total_cycles_executed": int(orch.total_cycles_executed),
            "latest_trace": traces[-1].to_dict() if traces else None,
            "uav_final_position": orch.uav_position,
            "emergency_stopped": orch.is_emergency_stopped,
        }
    )
    return result


def get_5g_slices_snapshot() -> dict[str, Any]:
    """Figures of the 5G slicing simulator held by this process's metaverse orchestrator.

    This is the same singleton the dashboard serves at ``/api/metaverse/slices``, so inside
    the dashboard process the two always agree. The MCP stdio server is normally a separate
    process: its orchestrator has run no cycle and cannot see the dashboard's traffic, which
    is reported as ``source: "fresh_simulation"`` instead of passing zeros off as live state.
    No radio is measured in either case.
    """
    from sovereign_dc.web.dashboard import get_metaverse_orchestrator

    orch = get_metaverse_orchestrator()
    cycles = int(orch.total_cycles_executed)
    snapshot: dict[str, Any] = {
        "timestamp": time.time(),
        "source": "process_orchestrator" if cycles > 0 else "fresh_simulation",
        "total_cycles_executed": cycles,
        "simulated": True,
        "slices": orch.slicing.get_summary(),
    }
    if cycles == 0:
        snapshot["note"] = (
            "No simulation cycle has run in this process, so the traffic counters are zero. "
            "A dashboard running in another process keeps its own state: read it from its "
            "/api/metaverse/slices endpoint."
        )
    return snapshot


def tool_get_5g_slices_status(params: dict[str, Any]) -> dict[str, Any]:
    """Returns the simulated 5G slice figures of this process's orchestrator (see ``get_5g_slices_snapshot``)."""
    snapshot = get_5g_slices_snapshot()
    snapshot["isolation_formula"] = "T_tx = (D * 8) / B_slice * 1000 ms"
    return snapshot


def tool_validate_depin_sla(params: dict[str, Any]) -> dict[str, Any]:
    """Tests DePIN smart contract SLA validation rules on specified or current UAV coordinates and receiver SINR values."""
    from sovereign_dc.metaverse.depin_sla import DePINSLAValidator

    val = DePINSLAValidator()
    uav_x = float(params.get("uav_x", 10.0))
    uav_y = float(params.get("uav_y", 15.0))
    uav_z = float(params.get("uav_z", 40.0))
    sinrs = params.get("receiver_sinrs", {"Rx1": -9.5, "Rx2": -7.8, "Rx3": -4.2})

    res = val.evaluate_uav_position_sla(
        uav_pos=(uav_x, uav_y, uav_z),
        per_receiver_sinr=sinrs,
        sensor_signatures_valid=bool(params.get("sensor_signatures_valid", True)),
    )

    return {
        "valid": res.valid,
        "position_approved": res.position_approved,
        "rejection_reason": res.rejection_reason,
        "min_sinr_db": res.min_sinr_db,
        "optimization_event_triggered": res.optimization_event_triggered,
        "validator_signatures_count": res.validator_signatures_count,
        "required_threshold": res.required_threshold,
        "block_hash": res.block_hash,
        "finality_time_sec": res.finality_time_sec,
    }
